import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
const root=new URL('../public/',import.meta.url);
const files=readdirSync(root,{recursive:true}).filter(file=>/\.(js|css|html|svg|png|webmanifest)$/.test(file)&&file!=='sw.js').sort();
const version=createHash('sha256');for(const file of files)version.update(file).update(readFileSync(new URL(file,root)));
const shell=files.map(file=>file==='index.html'?'/':'/'+file);
writeFileSync(new URL('sw.js',root),`// Generated by npm run service-worker. Cache only the public application shell.
const CACHE='readbook-shell-${version.digest('hex').slice(0,16)}';
const SHELL=${JSON.stringify(shell)};
self.addEventListener('install',event=>event.waitUntil((async()=>{
  const cache=await caches.open(CACHE);
  await cache.addAll(SHELL.map(url=>new Request(url,{cache:'reload'})));
})()));
self.addEventListener('activate',event=>event.waitUntil((async()=>{
  for(const key of await caches.keys())if(key.startsWith('readbook-shell-')&&key!==CACHE)await caches.delete(key);
  await self.clients.claim();
})()));
self.addEventListener('message',event=>{if(event.data?.type==='ACTIVATE_UPDATE')void self.skipWaiting();});
self.addEventListener('fetch',event=>{
  const url=new URL(event.request.url);
  if(event.request.method!=='GET'||url.origin!==self.location.origin||!SHELL.includes(url.pathname))return;
  event.respondWith((async()=>{
    const cache=await caches.open(CACHE);
    return await cache.match(url.pathname)||fetch(event.request);
  })());
});
`);
